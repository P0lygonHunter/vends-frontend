/**
 * Writes public/firebase-messaging-sw.js with VITE_FIREBASE_* at build time (Vercel).
 * ESM-compatible (client package.json has "type": "module").
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const cfg = {
  apiKey: process.env.VITE_FIREBASE_API_KEY || '',
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN || '',
  projectId: process.env.VITE_FIREBASE_PROJECT_ID || '',
  storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
  appId: process.env.VITE_FIREBASE_APP_ID || '',
}

const out = path.join(__dirname, '../public/firebase-messaging-sw.js')

if (!cfg.apiKey || !cfg.projectId) {
  fs.writeFileSync(
    out,
    `/* Firebase SW — config missing at build; push disabled */\nself.addEventListener('push', () => {});\n`
  )
  console.warn('[gen-firebase-sw] VITE_FIREBASE_* missing — noop SW written')
  process.exit(0)
}

const content = `/* Auto-generated by scripts/gen-firebase-sw.js — do not edit */
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(cfg, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || payload.data?.title || 'Vends EduCore';
  const options = {
    body: payload.notification?.body || payload.data?.body || '',
    icon: '/pwa-icon-192.png',
    badge: '/pwa-icon-192.png',
    data: payload.data || {},
  };
  self.registration.showNotification(title, options);
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const link = event.notification.data?.link || '/open';
  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((list) => {
      for (const c of list) {
        if ('focus' in c) {
          c.navigate(link);
          return c.focus();
        }
      }
      if (clients.openWindow) return clients.openWindow(link);
    })
  );
});
`

fs.writeFileSync(out, content)
console.log('[gen-firebase-sw] wrote', out)
