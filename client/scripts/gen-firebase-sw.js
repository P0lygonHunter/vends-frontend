/**
 * Writes public/firebase-messaging-sw.js at build time.
 * ALWAYS includes install + fetch handlers so Chrome PWA install criteria are met.
 * Optionally includes FCM when VITE_FIREBASE_* are present.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(__dirname, '../public/firebase-messaging-sw.js')
const shellOut = path.join(__dirname, '../public/sw.js')

const cfg = {
  apiKey: process.env.VITE_FIREBASE_API_KEY || '',
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN || '',
  projectId: process.env.VITE_FIREBASE_PROJECT_ID || '',
  storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
  appId: process.env.VITE_FIREBASE_APP_ID || '',
}

const SHELL = `/* Synapse EduCore — PWA shell + installability (fetch required by Chrome) */
const CACHE = 'synapse-shell-v3';
const SHELL_URLS = ['/manifest.webmanifest', '/pwa-icon-192.png', '/pwa-icon-512.png', '/favicon-32.png', '/open'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      try {
        const cache = await caches.open(CACHE);
        await Promise.all(SHELL_URLS.map((url) => cache.add(url).catch(() => null)));
      } catch (_) {}
      await self.skipWaiting();
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  let url;
  try { url = new URL(request.url); } catch (_) { return; }
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api')) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(async () => {
        const cached = await caches.match('/open');
        return cached || caches.match('/') || Response.error();
      })
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request)
        .then((res) => {
          try {
            if (res && res.ok && /\\.(png|webmanifest|js|css|svg|woff2?)$/i.test(url.pathname)) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(request, copy)).catch(() => {});
            }
          } catch (_) {}
          return res;
        })
        .catch(() => cached);
    })
  );
});
`

const hasFirebase = !!(cfg.apiKey && cfg.projectId)

const fcmPart = hasFirebase
  ? `
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(cfg, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  if (payload.notification && (payload.notification.title || payload.notification.body)) {
    return;
  }
  const title = (payload.data && payload.data.title) || 'SE Community';
  const options = {
    body: (payload.data && payload.data.body) || 'New message',
    icon: '/pwa-icon-192.png',
    badge: '/pwa-icon-192.png',
    tag: (payload.data && payload.data.tag) || 'se-community',
    renotify: true,
    data: payload.data || {},
  };
  self.registration.showNotification(title, options);
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const link = (event.notification.data && event.notification.data.link) || '/open';
  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((list) => {
      for (const c of list) {
        if ('focus' in c) {
          try { c.navigate(link); } catch (_) {}
          return c.focus();
        }
      }
      if (clients.openWindow) return clients.openWindow(link);
    })
  );
});
`
  : '\n/* FCM skipped — VITE_FIREBASE_* not set at build */\n'

const unified = `/* Auto-generated by scripts/gen-firebase-sw.js — do not edit by hand */\n${SHELL}\n${fcmPart}\n`

fs.writeFileSync(out, unified)
fs.writeFileSync(shellOut, `/* Mirror of installable SW without FCM binding name */\n${SHELL}\n`)
console.log('[gen-firebase-sw] wrote unified SW (fetch+install' + (hasFirebase ? '+FCM' : '') + ')')
